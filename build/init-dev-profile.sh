#!/usr/bin/env bash
# Bootstrap a developer sandbox profile under ~/.oiat/state/<profile>/.
#
# Creates an isolated state tree (companies JSON, logs, uploads, reports) and
# seeds a sandbox company config from the checked-in template. Does NOT touch
# production state or company configs.
#
# Usage:
#   ./build/init-dev-profile.sh                # defaults to "marvin-dev"
#   ./build/init-dev-profile.sh acme-dev       # custom profile name
#
# After running, edit:
#   .oiat/env/<profile>.env                    # env file with profile paths
#   ~/.oiat/state/<profile>/code_scripts/companies/company_sandbox.json
# Then run ./build/run-sandbox.sh (or OIAT_ENV_FILE=... ./build/run-local.sh).

set -euo pipefail

PROFILE_NAME="${1:-marvin-dev}"

if [[ ! "$PROFILE_NAME" =~ ^[a-zA-Z0-9._-]+$ ]]; then
  echo "Invalid profile name: $PROFILE_NAME (allowed: letters, digits, . _ -)"
  exit 1
fi

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

STATE_ROOT="$HOME/.oiat/state/$PROFILE_NAME"
COMPANIES_DIR="$STATE_ROOT/code_scripts/companies"
LOGS_DIR="$STATE_ROOT/code_scripts/logs"
UPLOADED_DIR="$STATE_ROOT/code_scripts/Uploaded"
REPORTS_DIR="$STATE_ROOT/code_scripts/reports"
UPLOADS_DIR="$STATE_ROOT/uploads"
ENV_DIR="$REPO_ROOT/.oiat/env"
ENV_FILE="$ENV_DIR/$PROFILE_NAME.env"
SANDBOX_TEMPLATE="$REPO_ROOT/code_scripts/companies/company_sandbox.example.json"
SANDBOX_TARGET="$COMPANIES_DIR/company_sandbox.json"

echo "==> Initialising developer profile: $PROFILE_NAME"
echo "    STATE_ROOT=$STATE_ROOT"

mkdir -p \
  "$COMPANIES_DIR" \
  "$LOGS_DIR/runs" \
  "$UPLOADED_DIR" \
  "$REPORTS_DIR" \
  "$UPLOADS_DIR/range_raw" \
  "$UPLOADS_DIR/spill_raw" \
  "$ENV_DIR"

if [ ! -f "$SANDBOX_TEMPLATE" ]; then
  echo "Missing sandbox template: $SANDBOX_TEMPLATE"
  echo "Did you check out the dev-stage-setup branch cleanly?"
  exit 1
fi

if [ -f "$SANDBOX_TARGET" ]; then
  echo "    company_sandbox.json already present — leaving untouched."
else
  cp "$SANDBOX_TEMPLATE" "$SANDBOX_TARGET"
  echo "    Seeded $SANDBOX_TARGET (edit before first run)."
fi

if [ -f "$ENV_FILE" ]; then
  echo "    $ENV_FILE already present — leaving untouched."
else
  cat > "$ENV_FILE" <<ENVEOF
# Developer sandbox profile: $PROFILE_NAME
# Generated by build/init-dev-profile.sh — edit placeholders before first run.
COMPOSE_PROJECT_NAME=oiat-$PROFILE_NAME

STATE_ROOT=~/.oiat/state/$PROFILE_NAME
OIAT_COMPANIES_DIR=~/.oiat/state/$PROFILE_NAME/code_scripts/companies
OIAT_RUNTIME_ENV=sandbox

# Intuit Development app credentials
QBO_CLIENT_ID=replace_with_intuit_development_client_id
QBO_CLIENT_SECRET=replace_with_intuit_development_client_secret

# Local Django settings
DJANGO_DEBUG=1
DJANGO_SECRET_KEY=replace-with-a-local-dev-secret
DJANGO_ALLOWED_HOSTS=localhost,127.0.0.1
DJANGO_CSRF_TRUSTED_ORIGINS=
DJANGO_USE_X_FORWARDED_PROTO=0
DJANGO_USE_X_FORWARDED_HOST=0
DJANGO_CSRF_COOKIE_SECURE=0
DJANGO_SESSION_COOKIE_SECURE=0

# Local web binding
WEB_BIND_HOST=127.0.0.1
WEB_BIND_PORT=8000

# Python 3.11 venv (see docs/DEV_STAGE_SETUP.md)
OIAT_VENV_PATH=~/.oiat/venv/$PROFILE_NAME
OIAT_RUNSERVER_ARGS=--noreload

# EPOS credentials — sandbox or read-only production login
EPOS_USERNAME_A=replace_with_sandbox_epos_username
EPOS_PASSWORD_A=replace_with_sandbox_epos_password

SLACK_WEBHOOK_URL_A=
SLACK_WEBHOOK_URL_B=

OIAT_SCHEDULER_POLL_SECONDS=15
OIAT_SCHEDULER_ENABLE_ENV_FALLBACK=1
SCHEDULE_CRON="0 18 * * *"
SCHEDULE_TZ=Africa/Lagos
ENVEOF
  chmod 600 "$ENV_FILE"
  echo "    Wrote $ENV_FILE (edit placeholders before first run)."
fi

cat <<NEXT

Next steps:
  1. Edit $ENV_FILE and fill in QBO_CLIENT_*, DJANGO_SECRET_KEY, EPOS_*.
  2. Edit $SANDBOX_TARGET with your sandbox realm_id, tax ids, etc.
  3. Build the Python 3.11 venv (only once):
       uv python install 3.11
       uv venv --python 3.11 ~/.oiat/venv/$PROFILE_NAME
       ~/.oiat/venv/$PROFILE_NAME/bin/python -m ensurepip --upgrade
       ~/.oiat/venv/$PROFILE_NAME/bin/python -m pip install -r requirements.txt
       ~/.oiat/venv/$PROFILE_NAME/bin/python -m playwright install chromium
  4. Start the portal:
       OIAT_ENV_FILE=$ENV_FILE ./build/run-local.sh
     Or (when profile name is marvin-dev):
       ./build/run-sandbox.sh

NEXT
